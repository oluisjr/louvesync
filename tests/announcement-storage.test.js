import test from 'node:test';
import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
import { publishAnnouncement, verifyAnnouncement, restoreAnnouncementCache, reconcileAnnouncements } from '../src/lib/announcement-storage.js';

const post = { id: 'post_local', title: 'Louvor novo', content: 'Vamos estudar o arranjo.', created_by: 'admin-fixture', created_at: '2026-11-13T18:35:00.000Z' };
function fixture(initial = []) {
  const state = { rows: structuredClone(initial), calls: [], generatedId: null, identityColumn: false, lostResponse: false, ghostResponse: false, readFailure: false };
  const client = createClient('https://fixture.supabase.co', 'fixture-public-key', {
    auth: { persistSession: false }, global: { fetch: async (target, options = {}) => {
      const url = new URL(target), method = options.method || 'GET';
      const body = options.body ? JSON.parse(options.body) : null;
      state.calls.push({ method, url, body });
      if (method === 'GET') {
        if (state.readFailure) return Response.json({ code: '57014', message: 'Read unavailable' }, { status: 400 });
        const rows = state.rows.filter(row => [...url.searchParams].every(([key, value]) => {
          if (!value.startsWith('eq.')) return true;
          const expected = value.slice(3);
          return key === 'created_at' ? Date.parse(row[key]) === Date.parse(expected) : String(row[key]) === expected;
        }));
        return Response.json(rows);
      }
      assert.equal(method, 'POST');
      if (state.identityColumn && body.id != null) return Response.json({ code: '22P02', message: 'ID must be generated by the database' }, { status: 400 });
      if (state.rows.some(row => String(row.id) === String(body.id))) return Response.json({ code: '23505', message: 'Duplicate ID' }, { status: 409 });
      const row = { ...body, id: state.generatedId ?? body.id ?? 1001 };
      if (!state.ghostResponse) state.rows.push(row);
      if (state.lostResponse) { state.lostResponse = false; return Response.json({ code: 'UPSTREAM_UNAVAILABLE', message: 'Response lost after commit' }, { status: 503 }); }
      return Response.json(row, { status: 201 });
    } },
  });
  return { client, state };
}

test('publication returns the independently read database row, not just the insert representation', async () => {
  const { client, state } = fixture();
  state.generatedId = 'persisted-post';
  const saved = await publishAnnouncement(client, { ...post, pendingSync: true, _publication: 'pending' });
  assert.equal(saved.id, 'persisted-post'); assert.equal(saved._publication, 'confirmed');
  assert.equal(saved.pendingSync, false);
  assert.deepEqual(state.calls.map(call => call.method), ['GET', 'POST', 'GET']);
  assert.equal(state.calls.at(-1).url.searchParams.get('id'), 'eq.persisted-post');
  assert.ok(!Object.hasOwn(state.calls[1].body, '_publication'));
  assert.ok(!Object.hasOwn(state.calls[1].body, 'pendingSync'));
});

test('an insert response without a persisted row cannot confirm a publication', async () => {
  const { client, state } = fixture(); state.ghostResponse = true;
  await assert.rejects(publishAnnouncement(client, post), error => error.code === 'ANNOUNCEMENT_NOT_CONFIRMED');
  assert.equal(state.rows.length, 0);
});

test('UUID and identity schemas can generate a persisted ID instead of accepting the local ID', async () => {
  const { client, state } = fixture(); state.identityColumn = true;
  const saved = await publishAnnouncement(client, post);
  assert.equal(saved.id, 1001);
  assert.equal(state.rows.length, 1);
  assert.ok(!Object.hasOwn(state.calls.filter(call => call.method === 'POST')[1].body, 'id'));
});

test('retrying the same draft after a lost acknowledgement finds its persisted row without duplicating it', async () => {
  const { client, state } = fixture(); state.generatedId = 'canonical-after-retry'; state.lostResponse = true;
  await assert.rejects(publishAnnouncement(client, post));
  assert.equal(state.rows.length, 1);
  const saved = await publishAnnouncement(client, post);
  assert.equal(saved.id, 'canonical-after-retry');
  assert.equal(state.calls.filter(call => call.method === 'POST').length, 1);
  assert.equal(state.rows.length, 1);
});

test('verification resolves a canonical ID only by exact publication identity and never republishes a missing post', async () => {
  const { client, state } = fixture([{ ...post, id: 501, created_at: '2026-11-13T18:35:00+00:00' }]);
  const saved = await verifyAnnouncement(client, post);
  assert.equal(saved.id, 501);
  assert.equal(await verifyAnnouncement(client, { ...post, content: 'Another message' }), null);
  assert.equal(await verifyAnnouncement(client, { ...post, created_by: 'someone-else' }), null);
  assert.ok(state.calls.every(call => call.method === 'GET'));
  state.readFailure = true;
  await assert.rejects(verifyAnnouncement(client, post), error => error.code === '57014');
});

test('cached posts require fresh verification; own missing text is preserved and unrelated deleted posts are removed', () => {
  const own = { ...post, _publication: 'confirmed' };
  const oldOther = { ...post, id: 'other-post', created_by: 'other-member' };
  const offline = { ...post, id: 'offline-post', title: 'Aviso offline', pendingSync: true };
  const restored = restoreAnnouncementCache([own, oldOther, offline]);
  assert.equal(restored[0]._publication, 'checking');
  assert.equal(restored[0]._previouslyConfirmed, true);
  assert.equal(restored[1]._previouslyConfirmed, false);
  assert.equal(restored[2]._publication, 'pending');
  const missing = reconcileAnnouncements(restored, [], post.created_by);
  assert.deepEqual(missing.map(row => [row.id, row._publication]), [['post_local', 'missing'], ['offline-post', 'pending']]);
  const reconciled = reconcileAnnouncements(restored, [{ ...post, id: 'canonical-post' }], post.created_by);
  assert.equal(reconciled.length, 2);
  assert.equal(reconciled[1].id, 'canonical-post');
  assert.equal(reconciled[1]._publication, 'confirmed');
});
